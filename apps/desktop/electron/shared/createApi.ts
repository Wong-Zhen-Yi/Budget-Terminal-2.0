import type { DesktopApi } from './contract.js'
import { CHANNELS } from './contract.js'

export type Invoke = <T>(channel: string, ...args: unknown[]) => Promise<T>
export type Subscribe = (channel: string, listener: () => void) => () => void

export function createApi(invoke: Invoke, subscribe: Subscribe, platform: NodeJS.Platform): DesktopApi {
  return {
    platform,
    apiUsage: () => invoke(CHANNELS.apiUsage),
    quotes: (request) => invoke(CHANNELS.quotes, request),
    chart: (request) => invoke(CHANNELS.chart, request),
    chartsHistory: (request) => invoke(CHANNELS.chartsHistory, request),
    chartsCompare: (request) => invoke(CHANNELS.chartsCompare, request),
    chartsRelationship: (request) => invoke(CHANNELS.chartsRelationship, request),
    options: (request) => invoke(CHANNELS.options, request),
    targets: (request) => invoke(CHANNELS.targets, request),
    news: (request) => invoke(CHANNELS.news, request),
    newsPage: (request) => invoke(CHANNELS.newsPage, request),
    newsTickerSearch: (request) => invoke(CHANNELS.newsTickerSearch, request),
    newsArticle: (request) => invoke(CHANNELS.newsArticle, request),
    newsThumbnail: (request) => invoke(CHANNELS.newsThumbnail, request),
    portfolio: () => invoke(CHANNELS.portfolio),
    mutatePortfolio: (mutation) => invoke(CHANNELS.portfolioMutate, mutation),
    cards: () => invoke(CHANNELS.cards),
    mutateCards: (mutation) => invoke(CHANNELS.cardsMutate, mutation),
    cardsPerformance: (request) => invoke(CHANNELS.cardsPerformance, request),
    personalFinance: () => invoke(CHANNELS.personalFinance),
    mutatePersonalFinance: (mutation) =>
      invoke(CHANNELS.personalFinanceMutate, mutation),
    fx: (request) => invoke(CHANNELS.fx, request),
    globalMarkets: (request) => invoke(CHANNELS.globalMarkets, request),
    preMarket: (request) => invoke(CHANNELS.preMarket, request),
    tradingVolumes: (request) => invoke(CHANNELS.tradingVolumes, request),
    signals: (request) => invoke(CHANNELS.signals, request),
    marketCapSales: (request) => invoke(CHANNELS.marketCapSales, request),
    marketCap: (request) => invoke(CHANNELS.marketCap, request),
    priceScreen: (request) => invoke(CHANNELS.priceScreen, request),
    calendarMonth: (request) => invoke(CHANNELS.calendarMonth, request),
    earningsCalendar: (request) => invoke(CHANNELS.earningsCalendar, request),
    forexQuotes: (request) => invoke(CHANNELS.forexQuotes, request),
    forexHistory: (request) => invoke(CHANNELS.forexHistory, request),
    forexNews: (request) => invoke(CHANNELS.forexNews, request),
    crypto: (request) => invoke(CHANNELS.crypto, request),
    bitcoin: (request) => invoke(CHANNELS.bitcoin, request),
    bmnr: (request) => invoke(CHANNELS.bmnr, request),
    sp500: (request) => invoke(CHANNELS.sp500, request),
    sp500Breadth: (request) => invoke(CHANNELS.sp500Breadth, request),
    gold: (request) => invoke(CHANNELS.gold, request),
    oil: (request) => invoke(CHANNELS.oil, request),
    heatmap: (request) => invoke(CHANNELS.heatmap, request),
    etfHoldings: (request) => invoke(CHANNELS.etfHoldings, request),
    etfArbitrage: (request) => invoke(CHANNELS.etfArbitrage, request),
    etfAum: (request) => invoke(CHANNELS.etfAum, request),
    upDown: (request) => invoke(CHANNELS.upDown, request),
    upDownTargets: (request) => invoke(CHANNELS.upDownTargets, request),
    stocks: (request) => invoke(CHANNELS.stocks, request),
    discoveryUniverse: () => invoke(CHANNELS.discoveryUniverse),
    discovery: (request) => invoke(CHANNELS.discovery, request),
    optionsChain: (request) => invoke(CHANNELS.optionsChain, request),
    optionsExpirations: (request) => invoke(CHANNELS.optionsExpirations, request),
    projections: (request) => invoke(CHANNELS.projections, request),
    valuation: (request) => invoke(CHANNELS.valuation, request),
    money: (request) => invoke(CHANNELS.money, request),
    economic: (request) => invoke(CHANNELS.economic, request),
    institutionActivity: (request) => invoke(CHANNELS.institutionActivity, request),
    institutionTickerActivity: (request) =>
      invoke(CHANNELS.institutionTickerActivity, request),
    roll: (request) => invoke(CHANNELS.roll, request),
    ipoUpcoming: (request) => invoke(CHANNELS.ipoUpcoming, request),
    ipoCompleted: (request) => invoke(CHANNELS.ipoCompleted, request),
    politicsPage: (request) => invoke(CHANNELS.politicsPage, request),
    politicsExport: (request) => invoke(CHANNELS.politicsExport, request),
    backtest: (request) => invoke(CHANNELS.backtest, request),
    quantScan: (request) => invoke(CHANNELS.quantScan, request),
    quantPair: (request) => invoke(CHANNELS.quantPair, request),
    youtube: (request) => invoke(CHANNELS.youtube, request),
    youtubeThumbnail: (request) => invoke(CHANNELS.youtubeThumbnail, request),
    fundamentals: (request) => invoke(CHANNELS.fundamentals, request),
    fundamentalsPage: (request) => invoke(CHANNELS.fundamentalsPage, request),
    returns: (request) => invoke(CHANNELS.returns, request),
    momentum: (request) => invoke(CHANNELS.momentum, request),
    analytics: (request) => invoke(CHANNELS.analytics, request),
    optionQuotes: (request) => invoke(CHANNELS.optionQuotes, request),
    settings: () => invoke(CHANNELS.settings),
    mutateSettings: (mutation) => invoke(CHANNELS.settingsMutate, mutation),
    maintenance: (action) => invoke(CHANNELS.maintenance, action),
    openExternal: (url) => invoke(CHANNELS.openExternal, url),
    saveText: (suggestedName, contents) =>
      invoke(CHANNELS.saveText, suggestedName, contents),
    writeClipboard: (contents) => invoke(CHANNELS.writeClipboard, contents),
    windowControl: (action) => invoke(CHANNELS.windowControl, action),
    onPortfolioChanged: (listener) => subscribe(CHANNELS.portfolioChanged, listener),
  }
}
